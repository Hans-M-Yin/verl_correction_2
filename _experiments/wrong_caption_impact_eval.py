"""
Evaluate whether carefully constructed wrong-caption samples truly reduce accuracy.

Experiment goal
---------------
For samples generated by `data/data_preprocess.py` with `extra_info.type == 1`,
run the same model twice:

1. Wrong-caption condition:
   keep the assistant-side wrong caption continuation and optionally append a
   randomly sampled reflection trigger.
2. Plain condition:
   remove the assistant-side caption and convert the sample back to a normal
   prompt.

Then:
- run batched vLLM inference for both conditions
- score both conditions with a copied reward implementation
- compare `acc_reward` between the two conditions
- analyze the wrong-caption samples that still get the answer correct

Reward note
-----------
This script does not reimplement the reward logic. Instead, it directly imports
and calls `_experiments/reward_function_loop.py`, which is copied from
`perception_2/reward_function_loop.py` and only replaces the judge backend with
`OpenAI().chat.completions.create(...)`.

Prompt construction note
------------------------
To let the model continue from the assistant-side caption, this script follows
the same idea as `verl/experimental/agent_loop.py::apply_chat_template`:

- call `processor.apply_chat_template(..., add_generation_prompt=True, tokenize=False)`
- if the last message role is `assistant`, remove the final `<|im_end|>`
  substring from the rendered prompt so generation continues from that point

Dataset format note
-------------------
The parquet dataset produced by `data/data_preprocess.py` contains, for each
sample:

- `prompt`: chat messages already constructed for training/inference
- `images`: a list containing one image
- `reward_model.ground_truth`: reference answer
- `extra_info.type`: 0 = no caption, 1 = wrong caption, 2 = correct caption
- `extra_info.question`: original question text
- `extra_info.answer`: original answer text
- `extra_info.caption_modified`: the wrong caption used for type=1
- `extra_info.modify_info` / `extra_info.num_modify`: correction metadata

This experiment only keeps `extra_info.type == 1` samples.
"""

