WRONG_CAPTION_CONDITION = "wrong_caption"
PLAIN_CONDITION = "plain"


def has_chinese(text: str) -> bool:
    return bool(re.search(r"[\u4e00-\u9fff]", text))


def load_triggers(triggers_file_path: str) -> dict[str, list[str]]:
    with open(triggers_file_path, "r", encoding="utf-8") as f:
        return json.load(f)


def sample_trigger(prompt: list[dict[str, Any]], triggers: dict[str, list[str]]) -> list[dict[str, Any]]:
    prompt_copy = copy.deepcopy(prompt)
    prompt_assistant = prompt_copy[-1]
    language = "english"

    if isinstance(prompt_assistant, str):
        language = "chinese" if has_chinese(prompt_assistant) else "english"
        prompt_assistant += " " + random.choice(triggers[language])
    elif isinstance(prompt_assistant, dict):
        if "content" not in prompt_assistant:
            raise ValueError("Assistant prompt dict must have `content`.")
        if isinstance(prompt_assistant["content"], list):
            if not prompt_assistant["content"]:
                raise ValueError("Assistant content list is empty.")
            last_item = prompt_assistant["content"][-1]
            if not isinstance(last_item, dict) or "text" not in last_item:
                raise ValueError(f"Unsupported assistant content item: {last_item}")
            language = "chinese" if has_chinese(last_item["text"]) else "english"
            last_item["text"] += " " + random.choice(triggers[language])
            prompt_assistant["content"][-1] = last_item
        elif isinstance(prompt_assistant["content"], str):
            language = "chinese" if has_chinese(prompt_assistant["content"]) else "english"
            prompt_assistant["content"] += " " + random.choice(triggers[language])
        else:
            raise ValueError(
                f"Unsupported assistant content type: {type(prompt_assistant['content'])}"
            )
    else:
        raise ValueError(f"Unsupported prompt item type: {type(prompt_assistant)}")

    prompt_copy[-1] = prompt_assistant
    return prompt_copy


@dataclass
class ExperimentSample:
    sample_id: str
    question: str
    ground_truth: str
    prompt: list[dict[str, Any]]
    image: PILImage.Image
    extra_info: dict[str, Any]


