def build_condition_summary(records: list[GenerationRecord]) -> dict[str, Any]:
    return {
        "num_samples": len(records),
        "accuracy": accuracy(records),
        "average_score": average_score(records),
        "format_error_rate": format_error_rate(records),
        "average_correction_reward": average_correction_reward(records),
    }


def main() -> None:
    args = parse_args()
    random.seed(args.seed)

    out_dir = ensure_output_dir(args.output_dir)
    write_json(out_dir / "run_args.json", vars(args))

    dataset = load_experiment_dataset(args.dataset_path, args.split)
    samples = filter_type_one_samples(dataset, args.max_samples)
    if not samples:
        raise RuntimeError("No `extra_info.type == 1` samples were found.")

    print(f"Loaded {len(samples)} type=1 wrong-caption samples.")

    reward_loop.init_openai_judge(
        api_key=args.api_key,
        base_url=args.base_url,
        judge_model=args.judge_model,
    )

    triggers = None if args.disable_trigger else load_triggers(args.trigger_file)
    sample_lookup = {sample.sample_id: sample for sample in samples}

    llm = LLM(
        model=args.model_path,
        trust_remote_code=True,
        tensor_parallel_size=args.tensor_parallel_size,
        limit_mm_per_prompt={"image": 1},
        gpu_memory_utilization=args.gpu_memory_utilization,
        enable_prefix_caching=True,
        max_num_seqs=512,
        max_model_len=args.max_model_len,
    )
    processor = Qwen2_5_VLProcessor.from_pretrained(
        args.model_path,
        trust_remote_code=True,
    )
    sampling_params = SamplingParams(
        temperature=0.0,
        top_k=1,
        n=1,
        max_tokens=args.max_tokens,
        skip_special_tokens=False,
    )

    wrong_inputs, wrong_meta = build_vllm_inputs(
        samples=samples,
        condition=WRONG_CAPTION_CONDITION,
        processor=processor,
        triggers=triggers,
        enable_trigger=not args.disable_trigger,
        trigger_prob=args.trigger_prob,
        save_prompts=args.save_prompts,
    )
    plain_inputs, plain_meta = build_vllm_inputs(
        samples=samples,
        condition=PLAIN_CONDITION,
        processor=processor,
        triggers=None,
        enable_trigger=False,
        trigger_prob=0.0,
        save_prompts=args.save_prompts,
    )

    wrong_records = run_generation(
        llm=llm,
        sampling_params=sampling_params,
        inputs=wrong_inputs,
        meta=wrong_meta,
        chunk_size=args.chunk_size,
    )
    plain_records = run_generation(
        llm=llm,
        sampling_params=sampling_params,
        inputs=plain_inputs,
        meta=plain_meta,
        chunk_size=args.chunk_size,
    )

    wrong_records = score_records(
        records=wrong_records,
        sample_lookup=sample_lookup,
        condition=WRONG_CAPTION_CONDITION,
        concurrency=args.score_concurrency,
    )
    plain_records = score_records(
        records=plain_records,
        sample_lookup=sample_lookup,
        condition=PLAIN_CONDITION,
        concurrency=args.score_concurrency,
    )

    wrong_summary = build_condition_summary(wrong_records)
    plain_summary = build_condition_summary(plain_records)
    paired_counts = compute_paired_counts(wrong_records, plain_records)
    pvalue = mcnemar_exact_pvalue(
        b=paired_counts["wrong_only_correct"],
        c=paired_counts["plain_only_correct"],
    )
    correct_wrong_caption_analysis = analyze_correct_wrong_caption_samples(
        wrong_records=wrong_records,
        direct_think_word_threshold=args.direct_think_word_threshold,
        save_limit=args.save_limit_analysis_examples,
    )

    summary = {
        "num_type1_samples": len(samples),
        "wrong_caption": wrong_summary,
        "plain": plain_summary,
        "accuracy_drop": plain_summary["accuracy"] - wrong_summary["accuracy"],
        "score_gap": plain_summary["average_score"] - wrong_summary["average_score"],
        "paired_counts": paired_counts,
        "mcnemar_exact_pvalue": pvalue,
        "trigger_enabled": not args.disable_trigger,
        "trigger_prob": args.trigger_prob,
        "judge_model": args.judge_model,
        "model_path": args.model_path,
        "analysis": correct_wrong_caption_analysis,
    }

    write_json(out_dir / "summary.json", summary)
    write_json(out_dir / "correct_wrong_caption_analysis.json", correct_wrong_caption_analysis)
    write_jsonl(out_dir / "wrong_caption_records.jsonl", records_to_jsonl(wrong_records))
    write_jsonl(out_dir / "plain_records.jsonl", records_to_jsonl(plain_records))

    comparison_rows = []
    plain_map = {record.sample_id: record for record in plain_records}
    for wrong_record in wrong_records:
        plain_record = plain_map[wrong_record.sample_id]
        comparison_rows.append(
            {
                "sample_id": wrong_record.sample_id,
                "question": wrong_record.question,
                "ground_truth": wrong_record.ground_truth,
                "wrong_caption_response": wrong_record.response,
                "wrong_caption_score": wrong_record.score,
                "wrong_caption_acc_reward": wrong_record.acc_reward,
                "wrong_caption_correction_reward": wrong_record.correction_reward,
                "wrong_caption_format_reward": wrong_record.format_reward,
                "wrong_caption_repeat_penalty": wrong_record.repeat_penalty,
                "wrong_caption_trigger_added": wrong_record.trigger_added,
                "plain_response": plain_record.response,
                "plain_score": plain_record.score,
                "plain_acc_reward": plain_record.acc_reward,
                "plain_correction_reward": plain_record.correction_reward,
                "plain_format_reward": plain_record.format_reward,
                "plain_repeat_penalty": plain_record.repeat_penalty,
            }
        )
    write_jsonl(out_dir / "paired_comparison.jsonl", comparison_rows)

    print("=" * 100)
    print("Experiment finished.")
    print(f"Output directory: {out_dir}")
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
