def resolve_dataset_file(dataset_path: str, split: str) -> str:
    path = Path(dataset_path)
    if path.is_file():
        return str(path)
    candidate = path / f"{split}.parquet"
    if candidate.exists():
        return str(candidate)
    raise FileNotFoundError(
        f"Cannot resolve parquet file from `{dataset_path}` with split `{split}`. "
        f"Expected: {candidate}"
    )


def load_experiment_dataset(dataset_path: str, split: str) -> Dataset:
    parquet_path = resolve_dataset_file(dataset_path, split)
    return load_dataset("parquet", data_files=parquet_path, split="train")


def convert_image_obj(image_obj: Any) -> PILImage.Image:
    if isinstance(image_obj, PILImage.Image):
        return image_obj.convert("RGB")
    if isinstance(image_obj, dict):
        if "bytes" in image_obj:
            return PILImage.open(io.BytesIO(image_obj["bytes"])).convert("RGB")
        if "path" in image_obj and image_obj["path"]:
            return PILImage.open(image_obj["path"]).convert("RGB")
    raise TypeError(f"Unsupported image object type: {type(image_obj)} | value={image_obj}")


def extract_first_image(images_field: Any) -> PILImage.Image:
    if isinstance(images_field, list):
        if not images_field:
            raise ValueError("Sample has empty `images`.")
        return convert_image_obj(images_field[0])
    return convert_image_obj(images_field)


def normalize_prompt(prompt: Any) -> list[dict[str, Any]]:
    if not isinstance(prompt, list):
        raise TypeError(f"Expected prompt to be a list, got {type(prompt)}")
    normalized: list[dict[str, Any]] = []
    for item in prompt:
        if not isinstance(item, dict):
            raise TypeError(f"Expected prompt item to be dict, got {type(item)}")
        normalized.append(copy.deepcopy(item))
    return normalized


def make_sample_id(index: int, raw_sample: dict[str, Any]) -> str:
    extra_info = raw_sample.get("extra_info", {}) or {}
    idx_value = extra_info.get("idx", index)
    return str(idx_value)


def filter_type_one_samples(dataset: Dataset, max_samples: int) -> list[ExperimentSample]:
    collected: list[ExperimentSample] = []
    for index, raw_sample in enumerate(dataset):
        extra_info = raw_sample.get("extra_info", {}) or {}
        if extra_info.get("type") != 1:
            continue

        ground_truth = (
            (raw_sample.get("reward_model") or {}).get("ground_truth")
            or extra_info.get("answer")
            or ""
        )
        collected.append(
            ExperimentSample(
                sample_id=make_sample_id(index, raw_sample),
                question=str(extra_info.get("question", "")),
                ground_truth=str(ground_truth),
                prompt=normalize_prompt(raw_sample["prompt"]),
                image=extract_first_image(raw_sample["images"]),
                extra_info=copy.deepcopy(extra_info),
            )
        )
        if max_samples > 0 and len(collected) >= max_samples:
            break
    return collected


def convert_prompt_to_multimodal_messages(
    prompt: list[dict[str, Any]],
    image: PILImage.Image,
) -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = []
    for item in prompt:
        role = item["role"]
        content = item.get("content", "")
        if role == "user":
            if not isinstance(content, str):
                raise TypeError(f"User content should be string, got {type(content)}")
            messages.append(
                {
                    "role": "user",
                    "content": [
                        {"type": "image", "image": image},
                        {"type": "text", "text": content},
                    ],
                }
            )
        elif role in {"system", "assistant"}:
            messages.append({"role": role, "content": copy.deepcopy(content)})
        else:
            raise ValueError(f"Unsupported role in prompt: {role}")
    return messages


def build_wrong_caption_prompt(
    sample: ExperimentSample,
    triggers: dict[str, list[str]] | None,
    enable_trigger: bool,
    trigger_prob: float,
) -> tuple[list[dict[str, Any]], bool]:
    prompt = copy.deepcopy(sample.prompt)
    trigger_added = False
    if enable_trigger:
        if triggers is None:
            raise ValueError("Triggers are required when enable_trigger=True.")
        if random.random() < trigger_prob:
            prompt = sample_trigger(prompt, triggers)
            trigger_added = True
    messages = convert_prompt_to_multimodal_messages(prompt, sample.image)
    if messages[-1]["role"] != "assistant":
        raise ValueError("Wrong-caption prompt must end with assistant content for continuation.")
    return messages, trigger_added


def build_plain_prompt(sample: ExperimentSample) -> tuple[list[dict[str, Any]], bool]:
    prompt = copy.deepcopy(sample.prompt)
    if prompt and prompt[-1]["role"] == "assistant":
        prompt = prompt[:-1]
    messages = convert_prompt_to_multimodal_messages(prompt, sample.image)
    if messages[-1]["role"] == "assistant":
        raise ValueError("Plain prompt should not end with assistant.")
    return messages, False


def apply_chat_template_like_agent_loop(
    processor: Qwen2_5_VLProcessor,
    messages: list[dict[str, Any]],
) -> str:
    raw_prompt = processor.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=False,
    )
    if messages[-1]["role"] == "assistant":
        end_token = "<|im_end|>"
        if end_token in raw_prompt:
            raw_prompt = raw_prompt[: raw_prompt.rfind(end_token)]
    return raw_prompt


def build_vllm_inputs(
    samples: list[ExperimentSample],
    condition: str,
    processor: Qwen2_5_VLProcessor,
    triggers: dict[str, list[str]] | None,
    enable_trigger: bool,
    trigger_prob: float,
    save_prompts: bool,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    inputs: list[dict[str, Any]] = []
    meta: list[dict[str, Any]] = []

    for sample in tqdm(samples, desc=f"Preparing {condition} prompts"):
        if condition == WRONG_CAPTION_CONDITION:
            messages, trigger_added = build_wrong_caption_prompt(
                sample=sample,
                triggers=triggers,
                enable_trigger=enable_trigger,
                trigger_prob=trigger_prob,
            )
        elif condition == PLAIN_CONDITION:
            messages, trigger_added = build_plain_prompt(sample)
        else:
            raise ValueError(f"Unknown condition: {condition}")

        raw_prompt = apply_chat_template_like_agent_loop(processor, messages)
        image_data, video_data = process_vision_info(messages)
        if video_data is not None:
            raise ValueError("This experiment only supports image-only samples.")

        inputs.append(
            {
                "prompt": raw_prompt,
                "multi_modal_data": {"image": image_data},
            }
        )
        meta.append(
            {
                "sample_id": sample.sample_id,
                "condition": condition,
                "question": sample.question,
                "ground_truth": sample.ground_truth,
                "trigger_added": trigger_added,
                "raw_prompt": raw_prompt if save_prompts else None,
            }
        )

    return inputs, meta


def chunked(sequence: Sequence[Any], chunk_size: int) -> Iterator[Sequence[Any]]:
    for start in range(0, len(sequence), chunk_size):
        yield sequence[start : start + chunk_size]


def run_generation(
    llm: LLM,
    sampling_params: SamplingParams,
    inputs: list[dict[str, Any]],
    meta: list[dict[str, Any]],
    chunk_size: int,
) -> list[GenerationRecord]:
    records: list[GenerationRecord] = []
    for input_chunk, meta_chunk in zip(chunked(inputs, chunk_size), chunked(meta, chunk_size)):
        outputs = llm.generate(list(input_chunk), sampling_params=sampling_params)
        for output, record_meta in zip(outputs, meta_chunk):
            records.append(
                GenerationRecord(
                    sample_id=record_meta["sample_id"],
                    condition=record_meta["condition"],
                    question=record_meta["question"],
                    ground_truth=record_meta["ground_truth"],
                    response=output.outputs[0].text,
                    trigger_added=record_meta["trigger_added"],
                    prompt_debug=record_meta["raw_prompt"],
                )
            )
    return records


def build_reward_extra_info(raw_extra_info: dict[str, Any], condition: str) -> dict[str, Any]:
    extra_info = copy.deepcopy(raw_extra_info)
    if condition == PLAIN_CONDITION:
        extra_info["type"] = 0
    elif condition == WRONG_CAPTION_CONDITION:
        extra_info["type"] = 1
    else:
        raise ValueError(f"Unknown condition: {condition}")
    return extra_info


async def score_records_async(
    records: list[GenerationRecord],
    sample_lookup: dict[str, ExperimentSample],
    condition: str,
    concurrency: int,
) -> list[GenerationRecord]:
    semaphore = asyncio.Semaphore(concurrency)

    async def _score_one(record: GenerationRecord) -> None:
        sample = sample_lookup[record.sample_id]
        extra_info = build_reward_extra_info(sample.extra_info, condition)
        async with semaphore:
            reward_output = await reward_loop.compute_score(
                data_source="wrong_caption_impact_experiment",
                solution_str=record.response,
                ground_truth=record.ground_truth,
                extra_info=extra_info,
                reward_router_address="",
                reward_model_tokenizer=None,
            )
        record.score = float(reward_output["score"])
        record.acc_reward = float(reward_output["acc_reward"])
        record.correction_reward = float(reward_output["correction_reward"])
        record.format_reward = float(reward_output["format_reward"])
        record.repeat_penalty = float(reward_output["repeat_penalty"])

    tasks = [_score_one(record) for record in records]
    for future in tqdm(asyncio.as_completed(tasks), total=len(tasks), desc=f"Scoring {condition}"):
        await future
    return records


def score_records(
    records: list[GenerationRecord],
    sample_lookup: dict[str, ExperimentSample],
    condition: str,
    concurrency: int,
) -> list[GenerationRecord]:
    return asyncio.run(
        score_records_async(
            records=records,
            sample_lookup=sample_lookup,
            condition=condition,
            concurrency=concurrency,
        )
    )


def accuracy(records: list[GenerationRecord]) -> float:
    if not records:
        return 0.0
    return sum(float(record.acc_reward or 0.0) for record in records) / len(records)


def average_score(records: list[GenerationRecord]) -> float:
    if not records:
        return 0.0
    return sum(float(record.score or 0.0) for record in records) / len(records)


def format_error_rate(records: list[GenerationRecord]) -> float:
    if not records:
        return 0.0
    num_error = sum(1 for record in records if float(record.format_reward or 0.0) < 0)
    return num_error / len(records)


def average_correction_reward(records: list[GenerationRecord]) -> float:
    if not records:
        return 0.0
    return sum(float(record.correction_reward or 0.0) for record in records) / len(records)


def compute_paired_counts(
    wrong_records: list[GenerationRecord],
    plain_records: list[GenerationRecord],
) -> dict[str, int]:
    plain_map = {record.sample_id: record for record in plain_records}
    counts = {
        "both_correct": 0,
        "both_wrong": 0,
        "wrong_only_correct": 0,
        "plain_only_correct": 0,
    }
    for wrong_record in wrong_records:
        plain_record = plain_map[wrong_record.sample_id]
        wrong_correct = int(float(wrong_record.acc_reward or 0.0) > 0.5)
        plain_correct = int(float(plain_record.acc_reward or 0.0) > 0.5)
        if wrong_correct and plain_correct:
            counts["both_correct"] += 1
        elif wrong_correct and not plain_correct:
            counts["wrong_only_correct"] += 1
        elif not wrong_correct and plain_correct:
            counts["plain_only_correct"] += 1
        else:
            counts["both_wrong"] += 1
    return counts


def mcnemar_exact_pvalue(b: int, c: int) -> float:
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    prob = 0.0
    for i in range(0, k + 1):
        prob += math.comb(n, i) * (0.5 ** n)
    return min(1.0, 2.0 * prob)


def extract_generated_thought(response: str) -> str:
    if "</think>" in response:
        return response.split("</think>", 1)[0]
    if "<answer>" in response:
        return response.split("<answer>", 1)[0]
    return response


def word_count(text: str) -> int:
    english_words = re.findall(r"[A-Za-z]+(?:'[A-Za-z]+)?", text)
    chinese_chars = re.findall(r"[\u4e00-\u9fff]", text)
    return len(english_words) + len(chinese_chars)


def analyze_direct_answer_behavior(
    response: str,
    direct_think_word_threshold: int,
) -> dict[str, Any]:
    generated_thought = extract_generated_thought(response)
    normalized = generated_thought.strip()
    lowered = response.lower()

    reflection_keywords = [
        "wait",
        "double-check",
        "double check",
        "mistaken",
        "misinterpreted",
        "actually",
        "however",
        "let me",
        "recheck",
        "之前",
        "等等",
        "核对",
        "误判",
        "再看",
        "重新",
    ]
    correction_keywords = [
        "not",
        "instead",
        "actually",
        "rather than",
        "wrong",
        "correct",
        "不是",
        "而是",
        "错误",
        "正确",
        "改成",
    ]

    closed_think_immediately = bool(re.match(r"^\s*</think>", response))
    answer_very_early = "<answer>" in response and response.find("<answer>") <= 32
    has_reflection_keyword = any(keyword in lowered for keyword in reflection_keywords)
    has_correction_keyword = any(keyword in lowered for keyword in correction_keywords)
    generated_word_count = word_count(normalized)

    direct_answer_like = (
        (
            closed_think_immediately
            or answer_very_early
            or generated_word_count <= direct_think_word_threshold
        )
        and not has_reflection_keyword
        and not has_correction_keyword
    )

    return {
        "generated_thought": generated_thought,
        "generated_thought_word_count": generated_word_count,
        "closed_think_immediately": closed_think_immediately,
        "answer_very_early": answer_very_early,
        "has_reflection_keyword": has_reflection_keyword,
        "has_correction_keyword": has_correction_keyword,
        "direct_answer_like": direct_answer_like,
    }


def analyze_correct_wrong_caption_samples(
    wrong_records: list[GenerationRecord],
    direct_think_word_threshold: int,
    save_limit: int,
) -> dict[str, Any]:
    correct_records = [
        record for record in wrong_records if float(record.acc_reward or 0.0) > 0.5
    ]

    for record in correct_records:
        record.direct_answer_heuristic = analyze_direct_answer_behavior(
            response=record.response,
            direct_think_word_threshold=direct_think_word_threshold,
        )

    direct_records = [
        record
        for record in correct_records
        if record.direct_answer_heuristic
        and bool(record.direct_answer_heuristic["direct_answer_like"])
    ]

    return {
        "num_correct_under_wrong_caption": len(correct_records),
        "num_direct_answer_like": len(direct_records),
        "ratio_direct_answer_like": (
            len(direct_records) / len(correct_records) if correct_records else 0.0
        ),
        "common_pattern_hypothesis": (
            "Most correct wrong-caption samples look like direct-answer behavior without substantial extra thinking."
            if correct_records and (len(direct_records) / len(correct_records)) >= 0.5
            else "No dominant direct-answer pattern found by the current heuristic."
        ),
        "examples": [
            {
                "sample_id": record.sample_id,
                "question": record.question,
                "ground_truth": record.ground_truth,
                "response": record.response,
                "score": record.score,
                "acc_reward": record.acc_reward,
                "correction_reward": record.correction_reward,
                "format_reward": record.format_reward,
                "repeat_penalty": record.repeat_penalty,
                "trigger_added": record.trigger_added,
                "heuristic": record.direct_answer_heuristic,
            }
            for record in correct_records[:save_limit]
        ],
    }


def write_json(path: Path, obj: Any) -> None:
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)


def write_jsonl(path: Path, rows: Iterable[dict[str, Any]]) -> None:
    with open(path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


